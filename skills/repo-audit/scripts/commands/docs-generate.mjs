function reject(code, path, message) {
  throw new CommandError('failed', [{ code, path, message, fix: 'Correct the registered generator or markers, then review regenerated bytes through a selected change set.' }])
}

// Include ignored files and links: a Git status check misses their mutations.
async function projectState(root, watchDirectory = () => {}) {
  const records = []
  async function walk(directory, prefix = '') {
    watchDirectory(directory)
    for (const name of (await readdir(directory)).sort()) {
      if (name === '.git') continue
      const path = prefix + name
      const file = join(directory, name)
      const info = await lstat(file)
      const content = info.isSymbolicLink() ? await readlink(file) : info.isFile() ? hashBytes(await readFile(file)) : null
      records.push({ path, mode: info.mode, content })
      if (info.isDirectory()) await walk(file, path + '/')
    }
  }
  await walk(root)
  return hashBytes(canonicalJSON(records))
}

function sections(text, path) {
  const found = new Map()
  let opened = null
  for (const match of text.matchAll(/<!--\s*bstack:(?:generated|end)\b[\s\S]*?(?:-->|$)/g)) {
    const start = /^<!-- bstack:generated ([^\s<>]+) -->$/.exec(match[0])
    if (start) {
      if (opened) reject('nested-marker', path, 'Generated sections cannot nest.')
      if (found.has(start[1])) reject('duplicate-marker', path, `Duplicate generated marker: ${start[1]}`)
      opened = { id: start[1], start: match.index + match[0].length }
    } else if (match[0] === '<!-- bstack:end -->') {
      if (!opened) reject('unmatched-marker', path, 'End marker has no generated marker.')
      found.set(opened.id, { start: opened.start, end: match.index })
      opened = null
    } else reject('invalid-marker', path, 'Use exact generated and end marker syntax.')
  }
  if (opened) reject('unmatched-marker', path, `Generated marker has no end: ${opened.id}`)
  return found
}

export async function run(options) {
  const target = await resolveTarget(options)
  const { contract, path: contractPath } = await loadContract(target, options.contract)
  const documents = new Map()
  const destinations = new Map()
  for (const generator of contract.generators) {
    if (!/^[^\s<>]+$/.test(generator.id)) reject('invalid-marker-id', contractPath, 'Generator IDs must be single marker tokens.')
    const outputs = new Map()
    destinations.set(generator, outputs)
    for (const path of generator.outputPaths) {
      const resolved = await resolveFilePath(target.root, path)
      if (!documents.has(resolved)) {
        const bytes = await readFile(resolved)
        let original
        try { original = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes) } catch { reject('unsupported-format', path, 'Generated documents must be valid UTF-8.') }
        documents.set(resolved, { path, original, markers: sections(original, path), replacements: [] })
      }
      if (!documents.get(resolved).markers.has(generator.id)) reject('missing-marker', path, `Missing registered marker: ${generator.id}`)
      if (!outputs.has(resolved)) outputs.set(resolved, path)
    }
  }
  const controller = new AbortController()
  const cancel = () => controller.abort()
  process.on('SIGINT', cancel)
  process.on('SIGTERM', cancel)
  const results = []
  try {
    for (const generator of contract.generators) {
      const watchers = []
      let changed = false
      let watchError = null
      let execution
      try {
        const before = await projectState(target.root, directory => {
          const watcher = watch(directory, (event, filename) => { if (filename !== '.git') changed = true })
          watchers.push(watcher)
          watcher.on('error', error => { watchError = error })
        })
        execution = await runCommand(target, generator.command, { signal: controller.signal, exactOutput: true })
        const after = await projectState(target.root)
        await setImmediate()
        if (watchError) throw watchError
        if (changed || after !== before) reject('generator-mutated-project', generator.id, 'Generator changed project files; its read-only contract failed.')
      } finally {
        for (const watcher of watchers) watcher.close()
      }
      if (execution.status !== 'passed' || execution.outputTruncated) reject('generator-failed', generator.id, execution.error ?? 'Generator failed or its captured output was truncated.')
      if (execution.stdout.includes('\0')) reject('unsupported-format', generator.id, 'Generated sections cannot contain NUL bytes.')
      for (const [resolved, path] of destinations.get(generator)) {
        const document = documents.get(resolved)
        const marker = document.markers.get(generator.id)
        const current = document.original.slice(marker.start, marker.end)
        results.push({ id: generator.id, path, current: current === execution.stdout })
        document.replacements.push({ ...marker, content: execution.stdout })
      }
    }
  } finally {
    process.removeListener('SIGINT', cancel)
    process.removeListener('SIGTERM', cancel)
  }
  const inputs = { repo: target.root, contract: contractPath }
  if (options.check) return { inputs, status: results.every(result => result.current) ? 'passed' : 'failed',
    data: { sections: results }, problems: results.filter(result => !result.current).map(result => ({ code: 'stale-generated-section', path: result.path,
      message: `Generated section is stale: ${result.id}`, fix: 'Run docs generate, review its scratch proposals and apply a selected change set.' })) }
  const directory = await createScratch(target)
  const proposals = []
  for (const document of documents.values()) {
    const { path } = document
    let content = document.original
    for (const replacement of document.replacements.sort((a, b) => b.start - a.start)) content = content.slice(0, replacement.start) + replacement.content + content.slice(replacement.end)
    // Generated output cannot introduce ambiguous marker structure.
    const markers = sections(content, path)
    if (markers.size !== document.markers.size || [...document.markers.keys()].some(id => !markers.has(id))) reject('invalid-generated-markers', path, 'Generator output changed marker structure.')
    if (content === document.original) continue
    proposals.push({ path, originalHash: hashBytes(Buffer.from(document.original)), proposedHash: hashBytes(Buffer.from(content)),
      operation: 'replace-file', payload: { content }, proposedContent: content, diff: exactDiff(path, document.original, content) })
  }
  const file = join(directory, 'generated-proposals.json')
  await writeFile(file, JSON.stringify({ proposals }, null, 2) + '\n', { flag: 'wx' })
  return { inputs, data: { sections: results, path: file, proposalsPath: file, proposals,
    next: 'Select findings, bind these complete proposals to a reviewed change set, then use apply --plan <file> --dry-run and apply --plan <file>.' } }
}
