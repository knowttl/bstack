import test from 'node:test'
import assert from 'node:assert/strict'
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')

async function sandbox(t: import('node:test').TestContext, sources = ['runtime/beta.contract.md', 'install/alpha.contract.md']) {
  const directory = await mkdtemp(join(tmpdir(), 'bstack contract é '))
  t.after(() => rm(directory, { recursive: true, force: true }))
  for (const folder of ['scripts', 'docs', 'runtime', 'install']) await mkdir(join(directory, folder))
  await cp(join(root, 'scripts/generate-contract.ts'), join(directory, 'scripts/generate-contract.ts'))
  await writeFile(join(directory, 'docs/command-contract.sources.json'), JSON.stringify(sources))
  await writeFile(join(directory, 'runtime/beta.contract.md'), '## Beta\n\nBeta rule.\n')
  await writeFile(join(directory, 'install/alpha.contract.md'), '## Alpha\n\nAlpha rule.\n')
  return directory
}

function generate(directory: string, ...args: readonly string[]) {
  return spawnSync(process.execPath, [join(directory, 'scripts', 'generate-contract.ts'), ...args], { encoding: 'utf8', cwd: tmpdir() })
}

test('generation joins the listed contract files in their listed order under the title', async t => {
  const directory = await sandbox(t)
  assert.equal(generate(directory).status, 0)
  assert.equal(await readFile(join(directory, 'docs/command-contract.md'), 'utf8'), [
    '# Shared command contracts', '',
    '<!-- Generated by scripts/generate-contract.ts from the contract files listed in docs/command-contract.sources.json. Do not edit. -->', '',
    '## Beta', '', 'Beta rule.', '', '## Alpha', '', 'Alpha rule.', ''].join('\n'))
})

for (const [name, mutate] of [
  ['a changed contract file', (directory: string) => writeFile(join(directory, 'runtime/beta.contract.md'), '## Beta\n\nAnother rule.\n')],
  ['a hand edit to the combined document', async (directory: string) => writeFile(join(directory, 'docs/command-contract.md'),
    (await readFile(join(directory, 'docs/command-contract.md'), 'utf8')).replace('Alpha rule.', 'Edited.'))],
  ['a missing combined document', (directory: string) => rm(join(directory, 'docs/command-contract.md'))]
] satisfies [unknown, unknown][]) {
  test(`check fails for ${name} without writing and a regeneration repairs it`, async t => {
    const directory = await sandbox(t)
    assert.equal(generate(directory).status, 0)
    await mutate(directory)
    const before = await readFile(join(directory, 'docs/command-contract.md'), 'utf8').catch(() => null)
    const stale = generate(directory, '--check')
    assert.equal(stale.status, 1)
    assert.match(stale.stderr, /docs\/command-contract\.md is stale/)
    assert.equal(await readFile(join(directory, 'docs/command-contract.md'), 'utf8').catch(() => null), before)
    assert.equal(generate(directory).status, 0)
    assert.equal(generate(directory, '--check').status, 0)
  })
}

test('generation refuses a contract file missing from the source list', async t => {
  const directory = await sandbox(t, ['runtime/beta.contract.md'])
  const result = generate(directory)
  assert.equal(result.status, 1)
  assert.match(result.stderr, /docs\/command-contract\.sources\.json must list install\/alpha\.contract\.md/)
})

test('generation refuses a listed contract file that does not exist', async t => {
  const directory = await sandbox(t, ['runtime/beta.contract.md', 'install/alpha.contract.md', 'runtime/gamma.contract.md'])
  const result = generate(directory)
  assert.equal(result.status, 1)
  assert.match(result.stderr, /gamma\.contract\.md/)
})

test('the committed combined document matches the contract files', () => {
  const result = spawnSync(process.execPath, [join(root, 'scripts', 'generate-contract.ts'), '--check'], { encoding: 'utf8', cwd: tmpdir() })
  assert.equal(result.status, 0, result.stderr)
})
