import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const output = 'docs/command-contract.md'
const order = 'docs/command-contract.sources.json'
const heading = `# Shared command contracts\n\n<!-- Generated by scripts/generate-contract.ts from the contract files listed in ${order}. Do not edit. -->`

try {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: node scripts/generate-contract.ts [--check]')
  const sources: string[] = JSON.parse(await readFile(join(root, order), 'utf8'))
  const unlisted = (await readdir(root, { recursive: true }))
    .map(path => path.split('\\').join('/'))
    .filter(path => path.endsWith('.contract.md') && !path.split('/').some(part => part === 'node_modules' || part.startsWith('.')) && !sources.includes(path))
  if (unlisted.length) throw new Error(`${order} must list ${unlisted.sort().join(', ')}`)
  const sections = await Promise.all(sources.map(async path => (await readFile(join(root, path), 'utf8')).trim()))
  const next = [heading, ...sections].join('\n\n') + '\n'
  const current = await readFile(join(root, output), 'utf8').catch(error => error.code === 'ENOENT' ? null : Promise.reject(error))
  if (next === current) console.log(`${output} is current`)
  else if (args[0] === '--check') throw new Error(`${output} is stale\nRun node scripts/generate-contract.ts`)
  else {
    await writeFile(join(root, output), next)
    console.log(`Generated ${output}`)
  }
} catch (error) {
  console.error((error as Error).message)
  process.exitCode = 1
}
