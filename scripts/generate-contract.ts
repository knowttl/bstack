import { readdir, readFile, realpath, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkLocalLink, markdownLinks } from '../runtime/scripts/lib/document-references.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const output = 'docs/command-contract.md'
const order = 'docs/command-contract.sources.json'
const commands = 'runtime/scripts/commands'
const heading = `# Shared command contracts\n\n<!-- Generated by scripts/generate-contract.ts from the contract files listed in ${order}. Do not edit. -->`
const posix = (path: string) => path.split('\\').join('/')
const codeSpan = /(```[\s\S]*?```|`[^`\n]*`)/
const linkDestination = /\]\(([^)\s]+)\)/g

function combinedHref(source: string, href: string, sources: string[]) {
  const hash = href.indexOf('#')
  const pathPart = hash < 0 ? href : href.slice(0, hash)
  const fragment = href.slice(hash < 0 ? href.length : hash)
  if (!pathPart || /^[A-Za-z][A-Za-z0-9+.-]*:|^\/\//.test(pathPart)) return href
  const target = posix(relative(root, resolve(root, dirname(source), pathPart)))
  if (sources.includes(target)) return fragment || href
  return posix(relative(join(root, 'docs'), join(root, target))) + (pathPart.endsWith('/') ? '/' : '') + fragment
}

function combine(source: string, text: string, sources: string[]) {
  return text.split(codeSpan).map((part, index) => index % 2 ? part : part.replace(linkDestination, (_, href: string) => `](${combinedHref(source, href, sources)})`)).join('')
}

async function linkProblems(path: string, text: string, documents?: Map<string, string>) {
  const problems: string[] = []
  for (const href of markdownLinks(text)) {
    const problem = await checkLocalLink(root, path, href, documents)
    if (problem) problems.push(`${path}:${text.split('\n').findIndex(line => line.includes(`](${href})`)) + 1}: contract-link: ${problem.message}. Use a link relative to ${dirname(path)} that names an existing file and heading.`)
  }
  return problems
}

async function missingContracts(sources: string[]) {
  const problems: string[] = []
  for (const name of await readdir(join(root, commands))) {
    if (!name.endsWith('.ts')) continue
    const contract = `${commands}/${name.replace(/\.ts$/, '.contract.md')}`
    if (!sources.includes(contract)) problems.push(`${commands}/${name}:1: command-contract-missing: command has no contract file listed in ${order}. Use ${contract} beside it and list it there.`)
  }
  return problems
}

try {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: node scripts/generate-contract.ts [--check]')
  const sources: string[] = JSON.parse(await readFile(join(root, order), 'utf8'))
  const unlisted = (await readdir(root, { recursive: true }))
    .map(path => path.split('\\').join('/'))
    .filter(path => path.endsWith('.contract.md') && !path.split('/').some(part => part === 'node_modules' || part.startsWith('.')) && !sources.includes(path))
  if (unlisted.length) throw new Error(`${order} must list ${unlisted.sort().join(', ')}`)
  const texts = await Promise.all(sources.map(path => readFile(join(root, path), 'utf8')))
  const next = [heading, ...sources.map((path, index) => combine(path, texts[index].trim(), sources))].join('\n\n') + '\n'
  const problems = [
    ...await missingContracts(sources),
    ...(await Promise.all(sources.map((path, index) => linkProblems(path, texts[index])))).flat(),
    ...await linkProblems(output, next, new Map([[join(await realpath(join(root, 'docs')), 'command-contract.md'), next]]))
  ]
  if (problems.length) throw new Error(problems.join('\n'))
  const current = await readFile(join(root, output), 'utf8').catch(error => error.code === 'ENOENT' ? null : Promise.reject(error))
  if (next === current) console.log(`${output} is current`)
  else if (args[0] === '--check') throw new Error(`${output} is stale\nRun node scripts/generate-contract.ts`)
  else {
    await writeFile(join(root, output), next)
    console.log(`Generated ${output}`)
  }
} catch (error) {
  console.error((error as Error).message)
  process.exitCode = 1
}
